from __future__ import annotations

from datetime import timedelta

from django.contrib.auth.hashers import check_password, make_password
from django.db import models
from django.utils import timezone


class TelegramOtp(models.Model):
    """
    OTP generated by Telegram bot and verified on the website.
    Stored hashed, time-limited, and with attempt limits.
    """

    phone_number = models.CharField(max_length=20, db_index=True)
    code_hash = models.CharField(max_length=256)
    created_at = models.DateTimeField(auto_now_add=True)
    expires_at = models.DateTimeField()
    attempts_used = models.PositiveIntegerField(default=0)
    max_attempts = models.PositiveIntegerField(default=5)
    is_used = models.BooleanField(default=False)

    class Meta:
        indexes = [
            models.Index(fields=["phone_number", "expires_at"], name="integrations_phone_expires_idx"),
        ]

    @classmethod
    def create_code(cls, phone_number: str, raw_code: str, ttl_minutes: int = 5) -> "TelegramOtp":
        now = timezone.now()
        return cls.objects.create(
            phone_number=phone_number,
            code_hash=make_password(raw_code),
            expires_at=now + timedelta(minutes=ttl_minutes),
        )

    def is_expired(self) -> bool:
        return timezone.now() >= self.expires_at

    def can_attempt(self) -> bool:
        return (not self.is_used) and (not self.is_expired()) and (self.attempts_used < self.max_attempts)

    def check_and_consume(self, raw_code: str) -> bool:
        if not self.can_attempt():
            return False
        self.attempts_used += 1
        ok = check_password(raw_code, self.code_hash)
        if ok:
            self.is_used = True
        self.save(update_fields=["attempts_used", "is_used"])
        return ok
