from __future__ import annotations

from django import forms
from django.contrib.auth import authenticate
from django.contrib.auth.password_validation import validate_password

from .models import User
from .utils import normalize_phone_number, validate_phone_number


class RegisterForm(forms.Form):
    phone_number = forms.CharField(max_length=20, widget=forms.TextInput(attrs={"autocomplete": "tel"}))
    telegram_code = forms.CharField(max_length=6, min_length=6, widget=forms.TextInput(attrs={"inputmode": "numeric"}))
    full_name = forms.CharField(max_length=200, required=False)
    password1 = forms.CharField(widget=forms.PasswordInput(attrs={"autocomplete": "new-password"}))
    password2 = forms.CharField(widget=forms.PasswordInput(attrs={"autocomplete": "new-password"}))

    def clean_phone_number(self):
        phone_number = normalize_phone_number(self.cleaned_data["phone_number"])
        if not validate_phone_number(phone_number):
            raise forms.ValidationError("Enter a valid phone number (e.g. +998901234567).")
        if User.objects.filter(phone_number=phone_number).exists():
            raise forms.ValidationError("This phone number is already registered.")
        return phone_number

    def clean(self):
        data = super().clean()
        password1 = data.get("password1") or ""
        password2 = data.get("password2") or ""
        if password1 != password2:
            self.add_error("password2", "Passwords do not match.")
        if password1:
            validate_password(password1)

        # Verify Telegram code (generated by bot)
        phone_number = data.get("phone_number") or ""
        code = (data.get("telegram_code") or "").strip()
        if phone_number and code and not self.errors:
            try:
                from integrations.models import TelegramOtp
                from django.db.utils import OperationalError

                otp = (
                    TelegramOtp.objects.filter(phone_number=phone_number, is_used=False)
                    .order_by("-created_at")
                    .first()
                )
                if not otp or not otp.check_and_consume(code):
                    self.add_error("telegram_code", "Invalid or expired Telegram code.")
            except OperationalError:
                self.add_error(None, "Database is not migrated. Run: python manage.py migrate")
        return data


class VerifyOtpForm(forms.Form):
    code = forms.CharField(max_length=6, min_length=6, widget=forms.TextInput(attrs={"inputmode": "numeric"}))


class LoginForm(forms.Form):
    phone_number = forms.CharField(max_length=20, widget=forms.TextInput(attrs={"autocomplete": "tel"}))
    password = forms.CharField(widget=forms.PasswordInput(attrs={"autocomplete": "current-password"}))

    def clean(self):
        data = super().clean()
        phone_number = normalize_phone_number(data.get("phone_number") or "")
        password = data.get("password") or ""
        user = authenticate(phone_number=phone_number, password=password)
        if not user:
            raise forms.ValidationError("Invalid phone number or password.")
        if not user.is_active or not user.is_phone_verified:
            raise forms.ValidationError("Your phone number is not verified yet.")
        data["user"] = user
        return data


class TelegramLoginForm(forms.Form):
    phone_number = forms.CharField(max_length=20, widget=forms.TextInput(attrs={"autocomplete": "tel"}))
    telegram_code = forms.CharField(max_length=6, min_length=6, widget=forms.TextInput(attrs={"inputmode": "numeric"}))

    def clean_phone_number(self):
        phone_number = normalize_phone_number(self.cleaned_data["phone_number"])
        if not validate_phone_number(phone_number):
            raise forms.ValidationError("Enter a valid phone number.")
        return phone_number

    def clean(self):
        data = super().clean()
        phone_number = normalize_phone_number(data.get("phone_number") or "")
        code = (data.get("telegram_code") or "").strip()
        if not phone_number or not code:
            return data

        try:
            from integrations.models import TelegramOtp
            from django.db.utils import OperationalError

            otp = (
                TelegramOtp.objects.filter(phone_number=phone_number, is_used=False)
                .order_by("-created_at")
                .first()
            )
            if not otp or not otp.check_and_consume(code):
                raise forms.ValidationError("Invalid or expired Telegram code.")
        except OperationalError:
            raise forms.ValidationError("Database is not migrated. Run: python manage.py migrate")

        user = User.objects.filter(phone_number=phone_number, is_active=True, is_phone_verified=True).first()
        if not user:
            raise forms.ValidationError("Account not found or not verified. Please register first.")

        data["user"] = user
        return data


